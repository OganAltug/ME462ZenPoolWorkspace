// Helper function to split a UTF-8 string into individual characters
inline std::vector<std::string> splitUTF8(const std::string& str) {
    std::vector<std::string> chars;
    for (size_t i = 0; i < str.length();) {
        int cplen = 1;
        if ((str[i] & 0xf8) == 0xf0) cplen = 4;
        else if ((str[i] & 0xf0) == 0xe0) cplen = 3;
        else if ((str[i] & 0xe0) == 0xc0) cplen = 2;
        
        chars.push_back(str.substr(i, cplen));
        i += cplen;
    }
    return chars;
}

